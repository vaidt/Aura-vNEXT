#!/usr/bin/env python3
"""Regenerate the M0 conformance vectors and the reference evidence package.

The vectors this writes are **known-answer tests generated by this implementation**.
They lock the canonical form against silent regression: any change to the encoder,
the field set, the ordering, or the confidence scale changes the recorded bytes and
fails the suite. They are not independent third-party vectors, and
docs/contract/M0-EVIDENCE-CONTRACT.md section 8 says so plainly. The bytes are
recorded in full precisely so that a human, or a second implementation, can review
them rather than trust a digest.

Standard library only (ADR-0002/ADR-0004).

Usage:
    python3 tools/build_m0_fixtures.py [--check]

``--check`` regenerates in memory and reports whether the committed files differ,
without writing. CI uses it to prove the fixtures match the implementation.
"""

from __future__ import annotations

