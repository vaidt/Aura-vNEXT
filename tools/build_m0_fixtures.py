VECTORS_PATH = REPO_ROOT / "conformance/vectors/m0-canonical-vectors.json"
PACKAGE_ROOT = REPO_ROOT / "evidence/examples/aura-evidence-loan-001"
PACKAGE_ID = "aura-evidence-loan-001"

H_A = "a" * 64
H_B = "b" * 64
H_C = "c" * 64


def _entry(**overrides) -> dict:
    """A representative entry, as the JSON-describable input a vector records."""
    base = {
        "seq": 0,
        "request_id": "req-0001",
        "timestamp": "2026-08-27T10:00:00Z",
        "decision": "DENY",
        "policy_hash": H_A,
        "policy_repr": "loan.underwriting/2",
        "input_hash": H_B,
        "prev_hash": GENESIS_PREV_HASH,
        "violations": [],
        "metadata": {},
        "shadow_hash": None,
        "schema": M0_AUDIT_SCHEMA,
    }
    base.update(overrides)
    return base


def _violation(rule: str, action: str, confidence: str) -> dict:
    # Confidence is recorded as a decimal *string* so the fixture states an exact
    # value rather than one mediated by JSON float parsing.
    return {"rule": rule, "action": action, "confidence": confidence}


def build_entry(spec: dict) -> AuditEntry:
    """Reconstruct an AuditEntry from a vector's recorded input."""
    return AuditEntry(
        seq=spec["seq"],
        request_id=spec["request_id"],
        timestamp=spec["timestamp"],
        decision=spec["decision"],
        policy_hash=spec["policy_hash"],
        policy_repr=spec["policy_repr"],
        input_hash=spec["input_hash"],
        prev_hash=spec["prev_hash"],
        violations=[
            Violation.build(v["rule"], v["action"], v["confidence"])
            for v in spec["violations"]
        ],
        metadata=dict(spec["metadata"]),
        shadow_hash=spec["shadow_hash"],
        schema=spec["schema"],
    )


